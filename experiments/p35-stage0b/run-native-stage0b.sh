STAGE0B_INITRAMFS="$(get_kv "$BUILD_OUT" INITRAMFS_OUT)"

CPIO_IMPLEMENTATION="$(get_kv "$BUILD_OUT" CPIO_IMPLEMENTATION)"
GZIP_IMPLEMENTATION="$(get_kv "$BUILD_OUT" GZIP_IMPLEMENTATION)"
INITRAMFS_EXTRACT="$(get_kv "$BUILD_OUT" INITRAMFS_EXTRACT)"
INITRAMFS_EXTRACT_RC="$(get_kv "$BUILD_OUT" INITRAMFS_EXTRACT_RC)"
ORIGINAL_INIT_PRESENT="$(get_kv "$BUILD_OUT" ORIGINAL_INIT_PRESENT)"
ORIGINAL_INIT_SHA="$(get_kv "$BUILD_OUT" ORIGINAL_INIT_SHA)"
STAGE0B_INIT_COPY="$(get_kv "$BUILD_OUT" STAGE0B_INIT_COPY)"
STAGE0B_INIT_CHMOD="$(get_kv "$BUILD_OUT" STAGE0B_INIT_CHMOD)"
STAGE0B_INIT_PRESENT="$(get_kv "$BUILD_OUT" STAGE0B_INIT_PRESENT)"
STAGE0B_BINSH_PRESENT="$(get_kv "$BUILD_OUT" STAGE0B_BINSH_PRESENT)"
STAGE0B_BINSH_EXECUTABLE="$(get_kv "$BUILD_OUT" STAGE0B_BINSH_EXECUTABLE)"
STAGE0B_BINSH_TARGET="$(get_kv "$BUILD_OUT" STAGE0B_BINSH_TARGET)"
BUSYBOX_PRESENT="$(get_kv "$BUILD_OUT" BUSYBOX_PRESENT)"
BUSYBOX_EXECUTABLE="$(get_kv "$BUILD_OUT" BUSYBOX_EXECUTABLE)"
BUSYBOX_MOUNT_APPLET_PRESENT="$(get_kv "$BUILD_OUT" BUSYBOX_MOUNT_APPLET_PRESENT)"
STAGE0B_MOUNT_COMMAND="$(get_kv "$BUILD_OUT" STAGE0B_MOUNT_COMMAND)"
STAGE0B_MOUNT_SYMLINK_VALID="$(get_kv "$BUILD_OUT" STAGE0B_MOUNT_SYMLINK_VALID)"

INITRAMFS_REPACK="$(get_kv "$BUILD_OUT" INITRAMFS_REPACK)"
INITRAMFS_REPACK_RC="$(get_kv "$BUILD_OUT" INITRAMFS_REPACK_RC)"
ORIGINAL_INIT_SHA_UNCHANGED="$(get_kv "$BUILD_OUT" ORIGINAL_INIT_SHA_UNCHANGED)"
INITRAMFS_VERIFY="$(get_kv "$BUILD_OUT" INITRAMFS_VERIFY)"
INITRAMFS_VERIFY_ERROR="$(get_kv "$BUILD_OUT" INITRAMFS_VERIFY_ERROR)"
BUILD_BLOCK_REASON="$(get_kv "$BUILD_OUT" BLOCK_REASON)"
[ -z "$BUILD_BLOCK_REASON" ] && BUILD_BLOCK_REASON="$(get_kv "$BUILD_OUT" INITRAMFS_BUILD_GATE_REASON)"

[ -z "$STAGE0B_BINSH_PRESENT" ] && STAGE0B_BINSH_PRESENT=UNKNOWN
[ -z "$STAGE0B_BINSH_EXECUTABLE" ] && STAGE0B_BINSH_EXECUTABLE=UNKNOWN
[ -z "$STAGE0B_BINSH_TARGET" ] && STAGE0B_BINSH_TARGET=UNKNOWN
[ -z "$BUSYBOX_PRESENT" ] && BUSYBOX_PRESENT=UNKNOWN
[ -z "$BUSYBOX_EXECUTABLE" ] && BUSYBOX_EXECUTABLE=UNKNOWN
[ -z "$BUSYBOX_MOUNT_APPLET_PRESENT" ] && BUSYBOX_MOUNT_APPLET_PRESENT=UNKNOWN
[ -z "$STAGE0B_MOUNT_COMMAND" ] && STAGE0B_MOUNT_COMMAND=UNKNOWN
[ -z "$STAGE0B_MOUNT_SYMLINK_VALID" ] && STAGE0B_MOUNT_SYMLINK_VALID=UNKNOWN

[ -z "$INITRAMFS_BUILD_GATE" ] && INITRAMFS_BUILD_GATE=FAIL
[ -z "$INITRAMFS_ORIGINAL_INIT_PRESERVED" ] && INITRAMFS_ORIGINAL_INIT_PRESERVED=UNKNOWN
[ -z "$INITRAMFS_STAGE0B_INIT" ] && INITRAMFS_STAGE0B_INIT=UNKNOWN
[ -z "$INITRAMFS_STAGE0B_INIT_EXECUTABLE" ] && INITRAMFS_STAGE0B_INIT_EXECUTABLE=UNKNOWN

if [ "$INITRAMFS_BUILD_GATE" != "PASS" ] || [ -z "$STAGE0B_INITRAMFS" ]; then
  if [ -n "$BUILD_BLOCK_REASON" ] && [ "$BUILD_BLOCK_REASON" != "NONE" ]; then
    BLOCK_REASON="$BUILD_BLOCK_REASON"
  else
    BLOCK_REASON="INITRAMFS_BUILD_FAILED"
