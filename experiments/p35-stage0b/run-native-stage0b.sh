# =================== cleanup trap ===================
cleanup() {
  # Exact-PID process cleanup (strictly forbidden: pkill -f / killall / pgrep -f)
  if [ -n "${STAGE0B_PID:-}" ]; then
    if kill -0 "$STAGE0B_PID" 2>/dev/null; then
      kill -TERM "$STAGE0B_PID" 2>/dev/null || true
      sleep 0.5
      if kill -0 "$STAGE0B_PID" 2>/dev/null; then
        kill -KILL "$STAGE0B_PID" 2>/dev/null || true
        sleep 0.2
      fi
      if kill -0 "$STAGE0B_PID" 2>/dev/null; then
        ORPHAN_PROCESS_COUNT=1
      else
        ORPHAN_PROCESS_COUNT=0
      fi
    else
      ORPHAN_PROCESS_COUNT=0
    fi
  else
    ORPHAN_PROCESS_COUNT=0
  fi

  # Optional console log preservation (for debugging rdinit/console failures)
  if [ "$PRESERVE_CONSOLE_LOG" = "1" ] && [ -n "${CANONICAL_RUN_ROOT:-}" ] && [ -n "${RUN_ID:-}" ]; then
    local src_log="$CANONICAL_RUN_ROOT/guest-console.log"
    local dest_log="/private/tmp/lmdr-p35-stage0b-debug-${RUN_ID}.log"
    if [ -f "$src_log" ] && [ ! -e "$dest_log" ]; then
      cp -f "$src_log" "$dest_log" 2>/dev/null || true
      if [ -f "$dest_log" ]; then
        chmod 0600 "$dest_log" 2>/dev/null || true
        CONSOLE_LOG_PRESERVED=YES
        CONSOLE_LOG_PATH="$dest_log"
        CONSOLE_LOG_SHA256="$(shasum -a 256 "$dest_log" 2>/dev/null | awk '{print $1}')"
        CONSOLE_LOG_BYTES="$(stat -f "%z" "$dest_log" 2>/dev/null || echo 0)"
      fi
    fi
  fi

  # Canonical /private/tmp Cleanup Gate (8 mandatory criteria)
  CLEANUP_PATH_GATE=FAIL
  TEMP_FILES_CLEANED=FAIL
  if [ -n "${CANONICAL_RUN_ROOT:-}" ] && [ -n "${RUN_ID:-}" ]; then
    local l_base="$(basename "$LOGICAL_RUN_ROOT" 2>/dev/null || echo "")"
    local c_base="$(basename "$CANONICAL_RUN_ROOT" 2>/dev/null || echo "")"
    local c_parent="$(dirname "$CANONICAL_RUN_ROOT" 2>/dev/null || echo "")"
    local c_verify="$(realpath "$CANONICAL_RUN_ROOT" 2>/dev/null || echo "")"

    local ok=1
    # 1. RUN_ID 非空
    [ -z "$RUN_ID" ] && ok=0
    # 2. logical basename 精确：lmdr-p35-stage0b-<RUN_ID>
    [ "$l_base" != "lmdr-p35-stage0b-$RUN_ID" ] && ok=0
    # 3. canonical basename 精确一致
    [ "$c_base" != "lmdr-p35-stage0b-$RUN_ID" ] && ok=0
    # 4. canonical parent 精确：/private/tmp
    [ "$c_parent" != "/private/tmp" ] && ok=0
    # 5. canonical path != /private/tmp
    [ "$CANONICAL_RUN_ROOT" = "/private/tmp" ] && ok=0
    # 6. canonical path != /tmp
    [ "$CANONICAL_RUN_ROOT" = "/tmp" ] && ok=0
    # 7. path 中不存在 unresolved ..
    case "$CANONICAL_RUN_ROOT" in *".."*) ok=0 ;; esac
    case "$LOGICAL_RUN_ROOT" in *".."*) ok=0 ;; esac
    # 8. directory 确实由本次 run 创建 (存在且 realpath 一致)
    [ ! -d "$CANONICAL_RUN_ROOT" ] && ok=0
    [ "$c_verify" != "$CANONICAL_RUN_ROOT" ] && ok=0

    if [ "$ok" = "1" ]; then
      CLEANUP_PATH_GATE=PASS
      if rm -rf -- "$CANONICAL_RUN_ROOT"; then
        if [ ! -e "$CANONICAL_RUN_ROOT" ]; then
          TEMP_FILES_CLEANED=PASS
        fi
      fi
    else
      CLEANUP_PATH_GATE=FAIL
      TEMP_FILES_CLEANED=FAIL
      echo "REFUSED unsafe rm of: $LOGICAL_RUN_ROOT (canonical=$CANONICAL_RUN_ROOT)" >&2
    fi
  fi

  # Baseline invariance check
  local proj_after="$(sha256_file "$PROJ_JSON")"
  local rt_after="$(sha256_file "$RT_JSON")"
  [ "$proj_after" != "$PROJ_SHA_BEFORE" ] && PROJECTS_JSON_MODIFIED=YES
  [ "$rt_after" != "$RT_SHA_BEFORE" ] && RUNTIME_MODIFIED=YES

  emit_report
}
