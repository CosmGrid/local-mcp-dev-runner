  STAGE0B_RESULT=BLOCKED
  echo "BUILD_OUT=$BUILD_OUT" >&2
  exit 2
fi

# =================== 4. build swift tool ===================
if ! BUILD_LINE="$("$HERE/build.sh" 2>&1)"; then
  STAGE0B_RESULT=FAIL
  BLOCK_REASON=swift_build_failed
  exit 2
fi
VZ_TOOL="$HERE/.build/stage0b-vz-tool"

# =================== 5. validate config ===================
KERNEL="${STAGE0A_KERNEL:-/tmp/lmdr-p35-stage0a-assets/vmlinuz-virt}"
CMD="console=hvc0 rdinit=/stage0b-init"
GUEST_COMMAND_LINE="$CMD"
VAL_JSON="$("$VZ_TOOL" validate --kernel "$KERNEL" --initrd "$STAGE0B_INITRAMFS" --share "$CANONICAL_RUN_ROOT/allowed" --cmdline "$CMD" 2>&1)"
VIRTIOFS_DEVICE="$(get_json "$VAL_JSON" virtiofsDevice)"
VIRTIOFS_TAG="$(get_json "$VAL_JSON" virtiofsTag)"
VIRTIOFS_SHARE_MODE="$(get_json "$VAL_JSON" virtiofsShareMode)"
NETWORK_DEVICE_COUNT="$(get_json "$VAL_JSON" networkDeviceCount)"
VAL_OK="$(get_json "$VAL_JSON" ok)"

[ -z "$VIRTIOFS_DEVICE" ] && VIRTIOFS_DEVICE=UNKNOWN
[ -z "$VIRTIOFS_TAG" ] && VIRTIOFS_TAG=UNKNOWN
[ -z "$VIRTIOFS_SHARE_MODE" ] && VIRTIOFS_SHARE_MODE=UNKNOWN
[ -z "$NETWORK_DEVICE_COUNT" ] && NETWORK_DEVICE_COUNT=UNKNOWN

if [ "$VAL_OK" != "true" ] || [ "$VIRTIOFS_TAG" != "lmdr-stage0b" ] || [ "$NETWORK_DEVICE_COUNT" != "0" ]; then
  STAGE0B_RESULT=FAIL
  BLOCK_REASON=config_validate_failed
  echo "VALIDATE_JSON=$VAL_JSON" >&2
  exit 2
fi

# =================== 6. run VM ===================
RUN_OUT_FILE="$CANONICAL_RUN_ROOT/.run.json"
CONSOLE_LOG_FILE="$CANONICAL_RUN_ROOT/guest-console.log"

"$VZ_TOOL" run --kernel "$KERNEL" --initrd "$STAGE0B_INITRAMFS" --share "$CANONICAL_RUN_ROOT/allowed" --cmdline "$CMD" --run-seconds 25 --console-log "$CONSOLE_LOG_FILE" > "$RUN_OUT_FILE" 2>&1 &
STAGE0B_PID=$!
wait "$STAGE0B_PID"

RUN_JSON="$(cat "$RUN_OUT_FILE" 2>/dev/null || echo "")"

VM_QUEUE_POLICY="$(get_json "$RUN_JSON" vmQueuePolicy)"
[ -z "$VM_QUEUE_POLICY" ] && VM_QUEUE_POLICY=UNKNOWN

VM_START="$(get_json "$RUN_JSON" vmStart)"
[ -z "$VM_START" ] && VM_START=UNKNOWN

VM_RUNNING="$(get_json "$RUN_JSON" vmRunning)"
[ -z "$VM_RUNNING" ] && VM_RUNNING=UNKNOWN

VM_STOP="$(get_json "$RUN_JSON" vmStop)"
[ -z "$VM_STOP" ] && VM_STOP=UNKNOWN

VM_FINAL_STATE="$(get_json "$RUN_JSON" vmFinalState)"
[ -z "$VM_FINAL_STATE" ] && VM_FINAL_STATE=UNKNOWN

CONSOLE_ATTACHMENT="$(get_json "$RUN_JSON" consoleAttachment)"
[ -z "$CONSOLE_ATTACHMENT" ] && CONSOLE_ATTACHMENT=UNKNOWN

CONSOLE_TOTAL_BYTES_SEEN="$(get_json "$RUN_JSON" consoleTotalBytesSeen)"
[ -z "$CONSOLE_TOTAL_BYTES_SEEN" ] && CONSOLE_TOTAL_BYTES_SEEN=0

CONSOLE_CAPTURE_BYTES="$(get_json "$RUN_JSON" consoleCaptureBytes)"
[ -z "$CONSOLE_CAPTURE_BYTES" ] && CONSOLE_CAPTURE_BYTES=0

CONSOLE_CAPTURE_TRUNCATED="$(get_json "$RUN_JSON" consoleCaptureTruncated)"
[ -z "$CONSOLE_CAPTURE_TRUNCATED" ] && CONSOLE_CAPTURE_TRUNCATED=UNKNOWN

GUEST_INIT_CONFIRMED_INLINE="$(get_json "$RUN_JSON" guestInitConfirmedInline)"
[ -z "$GUEST_INIT_CONFIRMED_INLINE" ] && GUEST_INIT_CONFIRMED_INLINE=UNKNOWN

GUEST_INIT_CONFIRMED_INLINE_TIMESTAMP_MS="$(get_json "$RUN_JSON" guestInitConfirmedInlineTimestampMs)"
[ -z "$GUEST_INIT_CONFIRMED_INLINE_TIMESTAMP_MS" ] && GUEST_INIT_CONFIRMED_INLINE_TIMESTAMP_MS=NOT_REPORTED

VM_STOP_TRIGGER="$(get_json "$RUN_JSON" vmStopTrigger)"
[ -z "$VM_STOP_TRIGGER" ] && VM_STOP_TRIGGER=UNKNOWN

VM_STOP_ORIGIN="$(get_json "$RUN_JSON" vmStopOrigin)"
[ -z "$VM_STOP_ORIGIN" ] && VM_STOP_ORIGIN=HOST_CONTROLLED

GUEST_INIT_STARTED="$(get_json "$RUN_JSON" guestInitStarted)"
[ -z "$GUEST_INIT_STARTED" ] && GUEST_INIT_STARTED=UNKNOWN

GUEST_PID1="$(get_json "$RUN_JSON" guestPid1)"
[ -z "$GUEST_PID1" ] && GUEST_PID1=UNKNOWN

GUEST_REPORT_COMPLETE="$(get_json "$RUN_JSON" guestReportComplete)"
[ -z "$GUEST_REPORT_COMPLETE" ] && GUEST_REPORT_COMPLETE=UNKNOWN

GUEST_REPORT_PARSE="$(get_json "$RUN_JSON" guestReportParse)"
[ -z "$GUEST_REPORT_PARSE" ] && GUEST_REPORT_PARSE=UNKNOWN

GUEST_REPORT_MALFORMED_LINES="$(get_json "$RUN_JSON" guestReportMalformedLines)"
[ -z "$GUEST_REPORT_MALFORMED_LINES" ] && GUEST_REPORT_MALFORMED_LINES=0

GUEST_REPORT_UNKNOWN_KEYS="$(get_json "$RUN_JSON" guestReportUnknownKeys)"
[ -z "$GUEST_REPORT_UNKNOWN_KEYS" ] && GUEST_REPORT_UNKNOWN_KEYS=0

VIRTIOFS_MOUNT="$(get_json "$RUN_JSON" virtiofsMount)"
[ -z "$VIRTIOFS_MOUNT" ] && VIRTIOFS_MOUNT=UNKNOWN

VIRTIOFS_MOUNT_RC="$(get_json "$RUN_JSON" virtiofsMountRc)"
[ -z "$VIRTIOFS_MOUNT_RC" ] && VIRTIOFS_MOUNT_RC=UNKNOWN

VIRTIOFS_MOUNT_ERROR="$(get_json "$RUN_JSON" virtiofsMountError)"
[ -z "$VIRTIOFS_MOUNT_ERROR" ] && VIRTIOFS_MOUNT_ERROR=NONE

VIRTIOFS_GUEST_SUPPORT="$(get_json "$RUN_JSON" virtiofsGuestSupport)"
[ -z "$VIRTIOFS_GUEST_SUPPORT" ] && VIRTIOFS_GUEST_SUPPORT=UNKNOWN

HOST_HOME_EXPOSED_TO_GUEST="$(get_json "$RUN_JSON" hostHomeExposedToGuest)"
[ -z "$HOST_HOME_EXPOSED_TO_GUEST" ] && HOST_HOME_EXPOSED_TO_GUEST=UNKNOWN

GUEST_HAS_VIRTIO_NET="$(get_json "$RUN_JSON" guestHasVirtioNet)"
[ -z "$GUEST_HAS_VIRTIO_NET" ] && GUEST_HAS_VIRTIO_NET=UNKNOWN

# Dual-channel result extraction (Console primary, share-backed file secondary)
GUEST_RESULTS="$(cat "$CANONICAL_RUN_ROOT/allowed/guest-results.txt" 2>/dev/null || echo "")"
GUEST_WRITE_FILE="$(cat "$CANONICAL_RUN_ROOT/allowed/guest-write.txt" 2>/dev/null || echo "")"

GUEST_READ_HOST_MARKER="$(get_json "$RUN_JSON" guestReadHostMarker)"
if [ "$GUEST_READ_HOST_MARKER" = "NOT_REPORTED" ] || [ -z "$GUEST_READ_HOST_MARKER" ]; then
  GUEST_READ_HOST_MARKER="$(get_kv "$GUEST_RESULTS" GUEST_READ_HOST_MARKER)"
fi
[ -z "$GUEST_READ_HOST_MARKER" ] && GUEST_READ_HOST_MARKER=UNKNOWN

GUEST_WRITE_MARKER="$(get_json "$RUN_JSON" guestWriteMarker)"
if [ "$GUEST_WRITE_MARKER" = "NOT_REPORTED" ] || [ -z "$GUEST_WRITE_MARKER" ]; then
  GUEST_WRITE_MARKER="$(get_kv "$GUEST_RESULTS" GUEST_WRITE_MARKER)"
fi
[ -z "$GUEST_WRITE_MARKER" ] && GUEST_WRITE_MARKER=UNKNOWN

DOTDOT_ESCAPE="$(get_json "$RUN_JSON" dotdotEscape)"
if [ "$DOTDOT_ESCAPE" = "NOT_REPORTED" ] || [ -z "$DOTDOT_ESCAPE" ]; then
  DOTDOT_ESCAPE="$(get_kv "$GUEST_RESULTS" DOTDOT_ESCAPE)"
fi
[ -z "$DOTDOT_ESCAPE" ] && DOTDOT_ESCAPE=UNKNOWN

SYMLINK_ESCAPE_REL="$(get_json "$RUN_JSON" symlinkEscapeRel)"
if [ "$SYMLINK_ESCAPE_REL" = "NOT_REPORTED" ] || [ -z "$SYMLINK_ESCAPE_REL" ]; then
  SYMLINK_ESCAPE_REL="$(get_kv "$GUEST_RESULTS" SYMLINK_ESCAPE_REL)"
fi
[ -z "$SYMLINK_ESCAPE_REL" ] && SYMLINK_ESCAPE_REL=UNKNOWN

SYMLINK_ESCAPE_ABS="$(get_json "$RUN_JSON" symlinkEscapeAbs)"
if [ "$SYMLINK_ESCAPE_ABS" = "NOT_REPORTED" ] || [ -z "$SYMLINK_ESCAPE_ABS" ]; then
  SYMLINK_ESCAPE_ABS="$(get_kv "$GUEST_RESULTS" SYMLINK_ESCAPE_ABS)"
fi
[ -z "$SYMLINK_ESCAPE_ABS" ] && SYMLINK_ESCAPE_ABS=UNKNOWN

ABSOLUTE_PATH_ESCAPE="$(get_json "$RUN_JSON" absolutePathEscape)"
if [ "$ABSOLUTE_PATH_ESCAPE" = "NOT_REPORTED" ] || [ -z "$ABSOLUTE_PATH_ESCAPE" ]; then
  ABSOLUTE_PATH_ESCAPE="$(get_kv "$GUEST_RESULTS" ABSOLUTE_PATH_ESCAPE)"
fi
[ -z "$ABSOLUTE_PATH_ESCAPE" ] && ABSOLUTE_PATH_ESCAPE=UNKNOWN

# =================== 7. Stage 0B Gate Evaluation ===================
if [ "$VM_START" != "true" ] || [ "$VM_RUNNING" != "true" ] || [ "$VM_STOP" != "true" ]; then
  STAGE0B_RESULT=FAIL
  BLOCK_REASON=vm_lifecycle_failed
elif [ "$CONSOLE_CAPTURE_BYTES" = "0" ]; then
  STAGE0B_RESULT=INCONCLUSIVE
  BLOCK_REASON=CONSOLE_CAPTURE_EMPTY
elif [ "$GUEST_INIT_STARTED" != "YES" ]; then
  VIRTIOFS_GUEST_SUPPORT=UNPROVEN
  STAGE0B_RESULT=INCONCLUSIVE
  BLOCK_REASON=GUEST_INIT_NOT_CONFIRMED
elif [ "$GUEST_REPORT_PARSE" = "FAIL" ]; then
  STAGE0B_RESULT=INCONCLUSIVE
  BLOCK_REASON=GUEST_REPORT_PARSE_FAILED
elif [ "$VIRTIOFS_MOUNT" != "PASS" ]; then
  # Strictly evaluate mount failure reason before issuing any BLOCKED verdict
  if [ "$VIRTIOFS_MOUNT_ERROR" = "MOUNT_COMMAND_MISSING" ]; then
    VIRTIOFS_GUEST_SUPPORT=UNPROVEN
    STAGE0B_RESULT=INCONCLUSIVE
    BLOCK_REASON=MOUNT_COMMAND_MISSING
  elif [ "$VIRTIOFS_MOUNT_ERROR" = "UNKNOWN_FILESYSTEM" ] || [ "$VIRTIOFS_MOUNT_ERROR" = "NO_SUCH_DEVICE" ]; then
    VIRTIOFS_GUEST_SUPPORT=FAIL
    STAGE0B_RESULT=BLOCKED
    BLOCK_REASON=VIRTIOFS_GUEST_UNSUPPORTED
  elif [ -n "$VIRTIOFS_MOUNT_ERROR" ] && [ "$VIRTIOFS_MOUNT_ERROR" != "NONE" ]; then
    VIRTIOFS_GUEST_SUPPORT=UNPROVEN
    STAGE0B_RESULT=INCONCLUSIVE
    BLOCK_REASON="VIRTIOFS_MOUNT_FAILED_${VIRTIOFS_MOUNT_ERROR}"
  else
    VIRTIOFS_GUEST_SUPPORT=UNPROVEN
    STAGE0B_RESULT=INCONCLUSIVE
    BLOCK_REASON=VIRTIOFS_MOUNT_FAILED_OTHER
  fi
  # Unmounted state: no share IO or path escape data
  VIRTIOFS_HOST_TO_GUEST_READ=NOT_RUN
  VIRTIOFS_GUEST_TO_HOST_WRITE=NOT_RUN
  GATE_A_IO=NOT_RUN
  DOTDOT_ESCAPE=INCONCLUSIVE
  SYMLINK_ESCAPE_REL=INCONCLUSIVE
  SYMLINK_ESCAPE_ABS=INCONCLUSIVE
  SYMLINK_ESCAPE=INCONCLUSIVE
  ABSOLUTE_PATH_ESCAPE=INCONCLUSIVE
  VIRTIOFS_PATH_ESCAPE_GATE=INCONCLUSIVE
  GATE_B_SECURITY=INCONCLUSIVE
  STAGE0B_SECURITY_GATE=INCONCLUSIVE
else
  # VIRTIOFS_MOUNT = PASS
  VIRTIOFS_GUEST_SUPPORT=PASS
  BLOCK_REASON=NONE

  # --- IO gate ---
  if [ "$GUEST_READ_HOST_MARKER" = "$HOST_READ_MARKER" ]; then
    VIRTIOFS_HOST_TO_GUEST_READ=PASS
  else
    VIRTIOFS_HOST_TO_GUEST_READ=FAIL
  fi

  if [ -n "$GUEST_WRITE_MARKER" ] && [ "$GUEST_WRITE_MARKER" != "NOT_RUN" ] && [ "$GUEST_WRITE_FILE" = "$GUEST_WRITE_MARKER" ]; then
    VIRTIOFS_GUEST_TO_HOST_WRITE=PASS
  else
    VIRTIOFS_GUEST_TO_HOST_WRITE=FAIL
  fi

  if [ "$VIRTIOFS_HOST_TO_GUEST_READ" = "PASS" ] && [ "$VIRTIOFS_GUEST_TO_HOST_WRITE" = "PASS" ]; then
    GATE_A_IO=PASS
  else
    GATE_A_IO=FAIL
  fi

  # --- symlink escape combine ---
  if [ "$SYMLINK_ESCAPE_REL" = "PASS" ] && [ "$SYMLINK_ESCAPE_ABS" = "PASS" ]; then
    SYMLINK_ESCAPE=PASS
  elif [ "$SYMLINK_ESCAPE_REL" = "FAIL" ] || [ "$SYMLINK_ESCAPE_ABS" = "FAIL" ]; then
    SYMLINK_ESCAPE=FAIL
  else
    SYMLINK_ESCAPE=INCONCLUSIVE
  fi

  # --- path-escape gate ---
  if [ "$DOTDOT_ESCAPE" = "PASS" ] && [ "$SYMLINK_ESCAPE" = "PASS" ] && [ "$ABSOLUTE_PATH_ESCAPE" = "PASS" ]; then
    VIRTIOFS_PATH_ESCAPE_GATE=PASS
  elif [ "$DOTDOT_ESCAPE" = "FAIL" ] || [ "$SYMLINK_ESCAPE" = "FAIL" ] || [ "$ABSOLUTE_PATH_ESCAPE" = "FAIL" ]; then
    VIRTIOFS_PATH_ESCAPE_GATE=FAIL
  else
    VIRTIOFS_PATH_ESCAPE_GATE=INCONCLUSIVE
  fi

  # --- security gate B ---
  SEC_FAIL=0
  SEC_INCONCLUSIVE=0
  [ "$DOTDOT_ESCAPE" = "FAIL" ] && SEC_FAIL=1
  [ "$SYMLINK_ESCAPE" = "FAIL" ] && SEC_FAIL=1
  [ "$ABSOLUTE_PATH_ESCAPE" = "FAIL" ] && SEC_FAIL=1
  [ "$HOST_HOME_EXPOSED_TO_GUEST" = "YES" ] && SEC_FAIL=1
  [ "$NETWORK_DEVICE_COUNT" != "0" ] && SEC_FAIL=1
  [ "$GUEST_HAS_VIRTIO_NET" = "YES" ] && SEC_FAIL=1
  [ "$ORPHAN_PROCESS_COUNT" != "0" ] && SEC_FAIL=1

  [ "$DOTDOT_ESCAPE" = "INCONCLUSIVE" ] && SEC_INCONCLUSIVE=1
  [ "$SYMLINK_ESCAPE" = "INCONCLUSIVE" ] && SEC_INCONCLUSIVE=1
  [ "$ABSOLUTE_PATH_ESCAPE" = "INCONCLUSIVE" ] && SEC_INCONCLUSIVE=1
  [ "$HOST_HOME_EXPOSED_TO_GUEST" = "UNKNOWN" ] && SEC_INCONCLUSIVE=1
  [ "$GUEST_HAS_VIRTIO_NET" = "UNKNOWN" ] && SEC_INCONCLUSIVE=1

  if [ "$SEC_FAIL" = "1" ]; then
    GATE_B_SECURITY=FAIL
    STAGE0B_SECURITY_GATE=FAIL
  elif [ "$SEC_INCONCLUSIVE" = "1" ]; then
    GATE_B_SECURITY=INCONCLUSIVE
    STAGE0B_SECURITY_GATE=INCONCLUSIVE
  else
    GATE_B_SECURITY=PASS
    STAGE0B_SECURITY_GATE=PASS
  fi

  # --- final stage result ---
  if [ "$GATE_B_SECURITY" = "PASS" ] && [ "$GATE_A_IO" = "PASS" ] && [ "$VM_QUEUE_POLICY" = "PASS" ]; then
    STAGE0B_RESULT=PASS
  elif [ "$GATE_B_SECURITY" = "FAIL" ] || [ "$GATE_A_IO" = "FAIL" ] || [ "$VM_QUEUE_POLICY" = "FAIL" ]; then
    STAGE0B_RESULT=FAIL
  else
    STAGE0B_RESULT=INCONCLUSIVE
  fi
fi

exit 0
