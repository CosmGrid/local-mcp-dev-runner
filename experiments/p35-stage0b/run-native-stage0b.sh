    local rp="$(realpath "$target" 2>/dev/null || echo "")"
    local base="$(basename "$target")"
    local parent="$(dirname "$rp")"
    if [ "$rp" = "$target" ] && [ "$base" = "lmdr-p35-stage0b-EHAgh7" ] && [ "$parent" = "/private/tmp" ]; then
